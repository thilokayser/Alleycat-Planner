function getCurrentLanguage(){
  try{ return localStorage.getItem('alleycat:lang') || 'de'; }
  catch(e){ return 'de'; }
}
function setLanguage(lang){
  try{ localStorage.setItem('alleycat:lang', lang); }
  catch(e){ console.error('Sprache konnte nicht gespeichert werden', e); }
  render();
}
function t(key, params){
  const lang = getCurrentLanguage();
  const dict = translations[lang] || translations.de;
  let str = key.split('.').reduce((o, k) => o && o[k], dict)
    ?? key.split('.').reduce((o, k) => o && o[k], translations.de)
    ?? key;
  if(params){
    Object.keys(params).forEach(k => { str = str.replace(`{${k}}`, params[k]); });
  }
  return str;
}
